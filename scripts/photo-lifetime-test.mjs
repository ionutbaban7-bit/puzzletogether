import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { PhotoStore, PHOTO_TTL_MS } from "../src/photoStore.js";
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pt-photo-timer-"));
let store;
try {
  const expired = [];
  store = new PhotoStore(dir, { ttlMs: 80, onExpire: photo => expired.push(photo) });
  const file = crypto.randomUUID() + ".webp";
  fs.writeFileSync(path.join(dir, file), "test derivative");
  const upload = store.add(file, 300, 200);
  store.claim(file, upload.token);
  store.bind(file, "test-room");
  assert.throws(() => store.claim(file, upload.token), /unavailable/);
  const deadline = upload.expiresAt;
  await new Promise(resolve => setTimeout(resolve, 120));
  assert.equal(store.get(file), null);
  assert.equal(fs.existsSync(path.join(dir, file)), false, "Timer deletes the actual image bytes without any request");
  assert.equal(fs.existsSync(path.join(dir, file + ".json")), false);
  assert.equal(expired[0].roomId, "test-room");
  assert.equal(expired[0].expiresAt, deadline);
  console.log("PASS active timer deletes bound image and metadata without traffic");
  store.close();
  let time = 10000;
  store = new PhotoStore(dir, { now: () => time });
  const orphan = crypto.randomUUID() + ".webp";
  fs.writeFileSync(path.join(dir, orphan), "orphan image");
  const pending = store.add(orphan, 300, 200);
  store.close();
  time += PHOTO_TTL_MS - 1;
  store = new PhotoStore(dir, { now: () => time });
  assert.equal(store.get(orphan).expiresAt, pending.expiresAt, "Restart cannot extend the deadline");
  time++;
  assert.equal(store.get(orphan), null, "At exactly one hour the photo is gone");
  assert.equal(fs.existsSync(path.join(dir, orphan)), false);
  console.log("PASS exact 1h cutoff, abandoned-upload deletion and restart-stable deadline");
} finally { store?.close(); fs.rmSync(dir, { recursive: true, force: true }); }
